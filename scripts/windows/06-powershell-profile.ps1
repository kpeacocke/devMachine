# Configure console font for Nerd Font icons (PowerShell console)
Write-Host "`n[CONSOLE] Configuring console font for Nerd Font support..."
try {
    # Registry paths for PowerShell console configurations
    $consolePaths = @(
        "HKCU:\Console\%SystemRoot%_System32_WindowsPowerShell_v1.0_powershell.exe",
        "HKCU:\Console\C:_Program Files_PowerShell_7_pwsh.exe"
    )

    # Create registry paths if they don't exist
    foreach ($path in $consolePaths) {
        if (-not (Test-Path $path)) {
            New-Item -Path $path -Force | Out-Null
        }
    }

    # Font settings for JetBrains Mono Nerd Font with auto-detection
    $installedJetBrainsFonts = Get-ChildItem "$env:windir\Fonts" -Filter "*JetBrains*" -ErrorAction SilentlyContinue | Where-Object {
        $_.Name -match "NF.*Regular\.ttf$|Nerd.*Font.*Regular\.ttf$"
    }

    $fontName = if ($installedJetBrainsFonts) {
        $installedJetBrainsFonts[0].BaseName
    } else {
        "JetBrainsMono NF"  # Fallback
    }

    Write-Host "    Using font: $fontName" -ForegroundColor Gray

    $fontSettings = @{
        "FaceName" = $fontName
        "FontFamily" = 54  # Modern font family
        "FontSize" = 0x000C0000  # Size 12 (high word = height, low word = width)
        "FontWeight" = 400  # Normal weight
    }

    # Additional console improvements
    $consoleSettings = @{
        "QuickEdit" = 1        # Enable quick edit mode
        "InsertMode" = 1       # Insert mode enabled
        "HistoryBufferSize" = 50    # Command history size
        "NumberOfHistoryBuffers" = 4  # Number of history buffers
    }

    # Apply font and console settings
    foreach ($path in $consolePaths) {
        foreach ($setting in ($fontSettings + $consoleSettings).GetEnumerator()) {
            Set-ItemProperty -Path $path -Name $setting.Key -Value $setting.Value -Type DWord -ErrorAction SilentlyContinue
        }
    }

    Write-Host "  ✅ Console font configured for Nerd Font icons" -ForegroundColor Green
    Write-Host "    Restart PowerShell console to see proper Git icons" -ForegroundColor Gray
} catch {
    Write-Warning "Console font configuration failed: $_"
}

# Configure VS Code terminal font for Nerd Font icons
Write-Host "`n[VSCODE] Configuring VS Code terminal font..."
try {
    $vscodeSettingsPath = "$env:APPDATA\Code\User\settings.json"

    if (Test-Path $vscodeSettingsPath) {
        $vscodeSettings = Get-Content $vscodeSettingsPath -Raw | ConvertFrom-Json

        # Add or update terminal font settings
        if (-not $vscodeSettings.'terminal.integrated.fontFamily') {
            $vscodeSettings | Add-Member -MemberType NoteProperty -Name 'terminal.integrated.fontFamily' -Value 'JetBrainsMono Nerd Font' -Force
        } else {
            $vscodeSettings.'terminal.integrated.fontFamily' = 'JetBrainsMono Nerd Font'
        }

        if (-not $vscodeSettings.'terminal.integrated.fontSize') {
            $vscodeSettings | Add-Member -MemberType NoteProperty -Name 'terminal.integrated.fontSize' -Value 12 -Force
        }

        $vscodeSettings | ConvertTo-Json -Depth 10 | Set-Content $vscodeSettingsPath -Encoding UTF8
        Write-Host "  ✅ VS Code terminal font configured" -ForegroundColor Green
        Write-Host "    Reload VS Code terminal to see proper Git icons" -ForegroundColor Gray
    } else {
        Write-Host "  ℹ️  VS Code settings not found (run VS Code once to create)" -ForegroundColor Gray
    }
} catch {
    Write-Warning "VS Code font configuration failed: $_"
}

