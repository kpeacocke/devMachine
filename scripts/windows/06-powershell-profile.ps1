function which($name) {
    Get-Command $name -ErrorAction SilentlyContinue | Select-Object -ExpandProperty Source
}

function touch($file) {
    "" | Out-File $file -Encoding ASCII
}

function mkcd($dir) {
    New-Item -ItemType Directory -Path $dir -Force | Set-Location
}

function .. { Set-Location .. }
function ... { Set-Location ..\.. }
function .... { Set-Location ..\..\.. }

function Get-PublicIP {
    (Invoke-WebRequest -Uri "https://api.ipify.org" -UseBasicParsing).Content
}

function Get-LocalIP {
    Get-NetIPAddress -AddressFamily IPv4 |
        Where-Object { $_.InterfaceAlias -notlike "*Loopback*" } |
        Select-Object IPAddress, InterfaceAlias
}

function Update-Profile {
    . $PROFILE
    Write-Host "Profile reloaded!" -ForegroundColor Green
}

function Edit-Profile {
    code $PROFILE
}

function Find-File($pattern) {
    Get-ChildItem -Recurse -Filter $pattern -ErrorAction SilentlyContinue
}

function Find-InFile($pattern, $path = ".") {
    Get-ChildItem -Path $path -Recurse -File |
        Select-String -Pattern $pattern |
        Group-Object Path |
        Select-Object Name
}

function Get-DiskSpace {
    Get-Volume |
        Where-Object { $_.DriveLetter } |
        Select-Object DriveLetter,
            @{Name="Size(GB)";Expression={[math]::Round($_.Size/1GB,2)}},
            @{Name="Free(GB)";Expression={[math]::Round($_.SizeRemaining/1GB,2)}},
            @{Name="Free(%)";Expression={[math]::Round(($_.SizeRemaining/$_.Size)*100,2)}}
}

function Get-SystemInfo {
    $os = Get-CimInstance Win32_OperatingSystem
    $cpu = Get-CimInstance Win32_Processor
    $mem = Get-CimInstance Win32_PhysicalMemory

    [PSCustomObject]@{
        OS = $os.Caption
        Version = $os.Version
        Architecture = $os.OSArchitecture
        CPU = $cpu.Name
        Cores = $cpu.NumberOfCores
        "RAM(GB)" = [math]::Round(($mem | Measure-Object Capacity -Sum).Sum / 1GB, 2)
        Uptime = (Get-Date) - $os.LastBootUpTime
    }
}

function Clean-Path {
    $env:Path = ($env:Path -split ';' | Select-Object -Unique) -join ';'
    Write-Host "PATH cleaned and deduplicated" -ForegroundColor Green
}

# Docker helpers
function docker-clean {
    docker system prune -a --volumes -f
    Write-Host "Docker cleanup complete" -ForegroundColor Green
}

function docker-stopall {
    docker stop $(docker ps -aq)
}

function docker-rmall {
    docker rm $(docker ps -aq)
}

# Git helpers
function git-main {
    $mainBranch = git remote show origin | Select-String "HEAD branch" | ForEach-Object { $_.ToString().Split()[-1] }
    git checkout $mainBranch
}

function git-clean-branches {
    git fetch --prune
    git branch -vv | Select-String ': gone]' | ForEach-Object {
        $branch = $_.ToString().Trim().Split()[0]
        git branch -D $branch
    }
}

function git-undo {
    git reset --soft HEAD~1
}

